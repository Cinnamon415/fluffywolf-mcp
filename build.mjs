// Creates the shared secret, writes extension/config.js and packs dist/fluffywolf-mcp.xpi.
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = dirname(fileURLToPath(import.meta.url));
const tokenFile = join(root, ".token");
const port = Number(process.env.FLUFFYWOLF_MCP_PORT || 8767);
const span = 10; // one bridge port per concurrent agent: port .. port+span-1

// Your own build gets its own random secret, created once in .token; the server reads it from there. Nobody has to
// make up a token. `--release` is for the release workflow only: it builds with the public default.token.
const release = process.argv.includes("--release");
if (!release && !existsSync(tokenFile)) writeFileSync(tokenFile, randomBytes(32).toString("hex"), { mode: 0o600 });
const token = readFileSync(release ? join(root, "default.token") : tokenFile, "utf8").trim();

writeFileSync(join(root, "extension", "config.js"), `// generated by build.mjs\nvar FWMCP_CONFIG = ${JSON.stringify({ port, span, token })};\n`);

mkdirSync(join(root, "dist"), { recursive: true });
const xpi = join(root, "dist", "fluffywolf-mcp.xpi");
rmSync(xpi, { force: true });
execFileSync("zip", ["-r", "-X", "-q", xpi, "."], { cwd: join(root, "extension") });
console.log(`built ${xpi} (port ${port})`);
