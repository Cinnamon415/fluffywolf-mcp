// Chooses the shared secret, writes extension/config.js and packs dist/fluffywolf-mcp.xpi.
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = dirname(fileURLToPath(import.meta.url));
const tokenFile = join(root, ".token");
const port = Number(process.env.FLUFFYWOLF_MCP_PORT || 8767);
const span = 10; // one bridge port per concurrent agent: port .. port+span-1

// FLUFFYWOLF_MCP_TOKEN wins (the release build uses the public default.token); otherwise your own random secret
// is created once in .token, and the server picks it up from there.
const fromEnv = (process.env.FLUFFYWOLF_MCP_TOKEN || "").trim();
if (fromEnv && fromEnv.length < 32) throw new Error("FLUFFYWOLF_MCP_TOKEN must be at least 32 characters");
if (!fromEnv && !existsSync(tokenFile)) writeFileSync(tokenFile, randomBytes(32).toString("hex"), { mode: 0o600 });
const token = fromEnv || readFileSync(tokenFile, "utf8").trim();

writeFileSync(join(root, "extension", "config.js"), `// generated by build.mjs\nvar FWMCP_CONFIG = ${JSON.stringify({ port, span, token })};\n`);

mkdirSync(join(root, "dist"), { recursive: true });
const xpi = join(root, "dist", "fluffywolf-mcp.xpi");
rmSync(xpi, { force: true });
execFileSync("zip", ["-r", "-X", "-q", xpi, "."], { cwd: join(root, "extension") });
console.log(`built ${xpi} (port ${port})`);
